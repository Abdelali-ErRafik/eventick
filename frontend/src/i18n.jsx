export function fill(template, vars) {
  return template.replace(/\{(\w+)\}/g, (_, key) => String(vars[key] ?? ""));
}

const LOCALE_KEY = "eventick_locale";
const I18nContext = createContext(null);

/** Every locale the UI ships. Arabic is the only RTL one. */
export const LOCALES = ["fr", "en", "ar"];
/** Switcher label key per locale. */
export const LOCALE_LABELS = { fr: "langFr", en: "langEn", ar: "langAr" };
/** Fixed short labels, for places that render outside the i18n dictionaries. */
export const LOCALE_SHORT = { fr: "FR", en: "EN", ar: "عربي" };
const DICTS = { fr, en, ar };

export function I18nProvider({ children }) {
  const [locale, setLocaleState] = useState(() => {
    if (typeof window === "undefined") return "fr";
    const saved = localStorage.getItem(LOCALE_KEY);
    return LOCALES.includes(saved) ? saved : "fr";
  });

  useEffect(() => {
    document.documentElement.lang = locale;
    document.documentElement.dir = locale === "ar" ? "rtl" : "ltr";
  }, [locale]);

  const setLocale = (next) => {
    setLocaleState(next);
    try {
      localStorage.setItem(LOCALE_KEY, next);
    } catch {
      // ignore storage failures
    }
  };

  const t = (key) => (DICTS[locale] ?? fr)[key] ?? fr[key];
  const tf = (key, vars) => fill(t(key), vars);
  const value = { locale, t, tf, setLocale, dir: locale === "ar" ? "rtl" : "ltr" };

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n() {
  const ctx = useContext(I18nContext);
  if (!ctx) throw new Error("useI18n must be used within I18nProvider");
  return ctx;
}

