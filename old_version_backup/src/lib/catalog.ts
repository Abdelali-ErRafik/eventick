export function minPrice(event: EventItem) {
  return Math.min(...event.tiers.map((tier) => tier.price));
}

export function capacityOf(event: EventItem) {
  return event.tiers.reduce((sum, tier) => sum + tier.capacity, 0);
}

export function remainingOf(event: EventItem, sold: Record<string, number>) {
  return event.tiers.reduce((sum, tier) => sum + tierLeft(event, tier, sold), 0);
}

export function tierLeft(event: EventItem, tier: Tier, sold: Record<string, number>) {
  return Math.max(0, tier.remaining - (sold[`${event.slug}:${tier.id}`] ?? 0));
}

export function fillRatio(event: EventItem, sold: Record<string, number>) {
  const cap = capacityOf(event);
  if (!cap) return 0;
  return 1 - remainingOf(event, sold) / cap;
}

export function findStatic(slug: string) {
  return EVENTS.find((event) => event.slug === slug);
}

export function mapsUrl(event: EventItem) {
  const q = encodeURIComponent(`${event.venueFr}, ${event.address}`);
  return `https://www.google.com/maps/search/?api=1&query=${q}`;
}
